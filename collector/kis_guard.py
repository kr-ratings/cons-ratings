"""한국투자증권 · 한국금융지주와 그 계열사가 나오는 기사 거르기(사이트 운영 원칙).

제목에 그룹 이름이 나오면, 분명히 긍정적인 기사(조달 성공 · 주관 · 수주 · 협약 등)이고 부정적인 낱말이
하나도 없을 때만 남긴다. 판단이 애매하면 뺀다. 구글 뉴스 RSS는 제목만 주므로 제목으로 판단한다.
'신한투자증권'처럼 이름 일부가 겹치는 다른 회사는 걸리지 않게 한다.
"""
import re

# 한국금융지주 · 한국투자증권 · 한국투자신탁운용 · 한국투자밸류자산운용 · 한국투자저축은행 · 한국투자캐피탈 ·
# 한국투자파트너스 · 한국투자부동산신탁 · 한국투자리얼에셋운용 · 한국투자프라이빗에쿼티 · 한국투자액셀러레이터 등(약칭 '한투~' 포함)
GROUP = re.compile(r"한국투자|(?<![신대])한투|한국금융지주|한금지주|김남구|Korea\s*Investment|이큐파트너스|키아라\s*캐피탈", re.I)
NEG = re.compile(
    r"손실|적자|감소|하락|급락|부진|악화|둔화|연체|부실|리스크|위험|우려|논란|의혹|제재|징계|과징금|과태료|검사|조사|수사|압수|"
    r"소송|피소|고발|고소|배상|분쟁|사고|민원|불완전|횡령|배임|위반|경고|주의|부도|손상|충당금|대손|강등|하향|철회|무산|지연|"
    r"중단|취소|해지|미달|미매각|떠안|부담|실패|문제|비판|지적|갑질|해고|구조조정|감원|희망퇴직|축소|철수|탈락|패소|벌금|기소|"
    r"구속|송치|불법|편법|특혜|담합|먹튀|폭탄|쇼크|충격|경보|빨간불|적신호|비상|위기|흔들|추락|굴욕|망신|오류|장애|먹통|해킹|"
    r"유출|낙마|불발|물려|반토막|급감|역성장|하회|못 미|그쳐|그친|뒷걸음|주춤|발목|암초|잡음|진통|갈등|공방|거절|불허|반려|부적격|"
    r"경영유의|개선요구|기관경고|영업정지|직무정지|무더기|잇따라|또\s|결국|'?빨간|대규모 손|손해")
POS = re.compile(r"성공|주관|수주|선정|체결|협약|MOU|출시|1위|최대|흥행|완판|달성|흑자|수상|선도|확대|돌파|증가|호실적|역대|최초|"
                 r"조달|유치|완료|개소|오픈|상장|발행|공급|참여|맞손|손잡|협력|업무협약|인수금융|주선")


def kis_ok(title: str) -> bool:
    """True = 사이트에 올려도 되는 기사. 그룹 이름이 없으면 그대로 True."""
    t = title or ""
    if not GROUP.search(t):
        return True
    return bool(POS.search(t)) and not NEG.search(t)
